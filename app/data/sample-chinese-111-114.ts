const single = (year: number, number: number, stem: string, options: string[], answer: string, passage?: string[]): QuizQuestion => ({
  id: `${year}-chinese-${number}`,
  number,
  type: 'single',
  stem,
  ...(passage ? { passage } : {}),
  options: options.map((text, index) => ({ key: 'ABCD'[index]!, text })),
  answer,
  points: 2,
})

